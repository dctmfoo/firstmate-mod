#!/usr/bin/env node
// fixture-ts.mjs - turn the made-up fixtures/demo-home into a test
// fixture module, since `claude plugin test` runs with no file system.
// CONTRIBUTING.md owns fixture generation and handling of local captures.
//
// Usage: node scripts/fixture-ts.mjs <replay-dir> <out.ts> <EXPORT_NAME>

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const [dir, out, name] = process.argv.slice(2)
if (!dir || !out || !name) {
  console.error('usage: fixture-ts.mjs <replay-dir> <out.ts> <EXPORT_NAME>')
  process.exit(2)
}

const walk = root =>
  readdirSync(root).flatMap(entry => {
    const path = join(root, entry)
    return statSync(path).isDirectory() ? walk(path) : [path]
  })

const files = {}
for (const path of walk(dir).sort()) {
  const rel = relative(dir, path)
  if (rel.startsWith('bin/')) continue
  files[rel] = readFileSync(path, 'utf8')
}

const capture = JSON.parse(files['capture.json'] ?? '{}')
const body = `// Generated by scripts/fixture-ts.mjs from ${capture.source_home ?? "a replay home"},
// clock ${capture.started ?? "?"} to ${capture.ended ?? "?"}.
// Do not edit by hand; edit the replay home and regenerate.

import type { Replay } from './replay'

export const ${name}: Replay = ${JSON.stringify({ capture, files }, null, 2)}
`
writeFileSync(out, body)
console.log(`wrote ${out} (${Object.keys(files).length} files)`)
